"""Day 2 — Variables & Data Types.
Task: Store your details and print them.
"""

def main():
    name = "Your Name"
    age = 0
    height = 0.0
    is_student = True

    print(name, type(name))
    print(age, type(age))
    print(height, type(height))
    print(is_student, type(is_student))

if __name__ == "__main__":
    main()